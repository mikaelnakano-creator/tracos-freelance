function slot(input: {
  id: string;
  event: EventRecord;
  eventService: EventService;
  slotNumber: number;
  freelancerId: string | null;
  fee: number;
  status: EventProfessionalSlot["status"];
  mode?: EventProfessionalSlot["assignmentMode"];
  notes?: string | null;
}): EventProfessionalSlot {
  return {
    id: input.id,
    organizationId: input.event.organizationId,
    eventId: input.event.id,
    eventServiceId: input.eventService.id,
    slotNumber: input.slotNumber,
    assignmentMode: input.mode ?? (input.freelancerId ? "direct" : "open"),
    assignedFreelancerId: input.freelancerId,
    agreedFeeCents: input.fee,
    status: input.status,
    acceptedAt: input.freelancerId ? input.event.updatedAt : null,
    completedAt: input.status === "completed" ? input.event.completedAt : null,
    cancelledAt: null,
    cancellationReason: null,
    notes: input.notes ?? null,
    createdBy: demoProfiles[0].id,
    createdAt: input.event.createdAt,
    updatedAt: input.event.updatedAt,
  };
}

